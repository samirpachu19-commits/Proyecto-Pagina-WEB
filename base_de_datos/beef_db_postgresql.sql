-- ---------- VISTAS ----------

CREATE VIEW vista_menu AS
SELECT p.id_producto, c.nombre AS categoria, p.nombre, p.descripcion,
       p.precio, c.unidad_venta, p.imagen
FROM productos p
JOIN categorias c ON c.id_categoria = p.id_categoria
WHERE p.activo = TRUE
ORDER BY p.id_producto;

CREATE VIEW vista_pedidos AS
SELECT pe.id_pedido, pe.fecha_pedido,
       cl.nombre || ' ' || cl.apellido AS cliente,
       cl.telefono, pe.tipo_entrega, pe.estado, pe.metodo_pago, pe.total
FROM pedidos pe
JOIN clientes cl ON cl.id_cliente = pe.id_cliente;


-- ---------- RECETAS Y HORARIOS ----------
CREATE TABLE recetas (
    id_receta       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto     INT REFERENCES productos(id_producto) ON UPDATE CASCADE ON DELETE SET NULL,
    titulo          VARCHAR(120) NOT NULL,
    descripcion     VARCHAR(300),
    tiempo_minutos  INT          NOT NULL CHECK (tiempo_minutos > 0),
    porciones       INT          NOT NULL CHECK (porciones > 0),
    dificultad      VARCHAR(10)  NOT NULL CHECK (dificultad IN ('Fácil','Media','Difícil')),
    imagen          VARCHAR(150),
    ingredientes    TEXT         NOT NULL,
    preparacion     TEXT         NOT NULL,
    activo          BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------- 9. HORARIOS ----------
CREATE TABLE horarios (
    id_horario     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana     SMALLINT    NOT NULL UNIQUE CHECK (dia_semana BETWEEN 1 AND 7),
    nombre_dia     VARCHAR(30) NOT NULL,
    hora_apertura  TIME,
    hora_cierre    TIME,
    cerrado        BOOLEAN     NOT NULL DEFAULT FALSE,
    CHECK (cerrado OR (hora_apertura IS NOT NULL AND hora_cierre > hora_apertura))
);

CREATE INDEX idx_recetas_producto ON recetas(id_producto);

