-- ---------- BASE DE DATOS ----------

DROP VIEW  IF EXISTS vista_recetas, vista_pedidos, vista_menu;
DROP TABLE IF EXISTS detalle_pedido, pedidos, clientes, productos, categorias,
                     mensajes_contacto, usuarios, recetas, horarios CASCADE;

-- ---------- 1. CATEGORIAS ----------
CREATE TABLE categorias (
    id_categoria   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(50)  NOT NULL UNIQUE,
    descripcion    VARCHAR(255),
    unidad_venta   VARCHAR(10)  NOT NULL CHECK (unidad_venta IN ('plato','kg'))
);

-- ---------- 2. PRODUCTOS ----------
CREATE TABLE productos (
    id_producto    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria   INT           NOT NULL
                   REFERENCES categorias(id_categoria) ON UPDATE CASCADE ON DELETE RESTRICT,
    nombre         VARCHAR(100)  NOT NULL,
    descripcion    TEXT,
    precio         NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
    imagen         VARCHAR(150),
    stock_kg       NUMERIC(8,2),
    activo         BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- 3. CLIENTES ----------
CREATE TABLE clientes (
    id_cliente     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(80)  NOT NULL,
    apellido       VARCHAR(80)  NOT NULL,
    correo         VARCHAR(120) NOT NULL UNIQUE,
    telefono       VARCHAR(20),
    direccion      VARCHAR(200),
    ciudad         VARCHAR(80),
    fecha_registro TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- 4. PEDIDOS ----------
CREATE TABLE pedidos (
    id_pedido         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente        INT NOT NULL
                      REFERENCES clientes(id_cliente) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha_pedido      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_entrega      VARCHAR(15) NOT NULL DEFAULT 'domicilio'
                      CHECK (tipo_entrega IN ('domicilio','recoger','mesa')),
    direccion_entrega VARCHAR(200),
    estado            VARCHAR(15) NOT NULL DEFAULT 'pendiente'
                      CHECK (estado IN ('pendiente','preparando','enviado','entregado','cancelado')),
    metodo_pago       VARCHAR(15) NOT NULL DEFAULT 'efectivo'
                      CHECK (metodo_pago IN ('efectivo','tarjeta','nequi','daviplata','transferencia')),
    total             NUMERIC(12,2) NOT NULL DEFAULT 0,
    observaciones     VARCHAR(255)
);

-- ---------- 5. DETALLE_PEDIDO ----------
CREATE TABLE detalle_pedido (
    id_detalle      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido       INT NOT NULL
                    REFERENCES pedidos(id_pedido) ON UPDATE CASCADE ON DELETE CASCADE,
    id_producto     INT NOT NULL
                    REFERENCES productos(id_producto) ON UPDATE CASCADE ON DELETE RESTRICT,
    cantidad        NUMERIC(8,2)  NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2) NOT NULL,
    subtotal        NUMERIC(12,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
    CONSTRAINT uq_pedido_producto UNIQUE (id_pedido, id_producto)
);

-- ---------- 6. MENSAJES_CONTACTO ----------
CREATE TABLE mensajes_contacto (
    id_mensaje     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(80)  NOT NULL,
    correo         VARCHAR(120) NOT NULL,
    mensaje        TEXT         NOT NULL,
    fecha_envio    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    leido          BOOLEAN      NOT NULL DEFAULT FALSE
);

-- ---------- 7. USUARIOS ----------
CREATE TABLE usuarios (
    id_usuario      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80)  NOT NULL,
    usuario         VARCHAR(50)  NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,
    rol             VARCHAR(10)  NOT NULL DEFAULT 'empleado' CHECK (rol IN ('admin','empleado')),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_productos_categoria ON productos(id_categoria);
CREATE INDEX idx_pedidos_cliente     ON pedidos(id_cliente);
CREATE INDEX idx_pedidos_estado      ON pedidos(estado);


