SELECT setval(pg_get_serial_sequence('recetas','id_receta'), (SELECT MAX(id_receta) FROM recetas));

CREATE VIEW vista_recetas AS
SELECT r.id_receta, r.titulo, r.descripcion, r.tiempo_minutos, r.porciones, r.dificultad,
       r.imagen, r.ingredientes, r.preparacion,
       p.id_producto, p.nombre AS corte, p.precio AS precio_corte, p.imagen AS imagen_corte,
       p.activo AS corte_disponible
FROM recetas r
LEFT JOIN productos p ON p.id_producto = r.id_producto
WHERE r.activo = TRUE
ORDER BY r.id_receta;

